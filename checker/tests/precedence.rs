//! The operator precedence the Coq model of operator runs reads
//! (`proofs/GoatPrec.v`, ADR 0030). The table in `proofs/GoatPrecTable.v` is
//! observed from lowering, not copied from `lower.rs`: for every operator
//! already on lowering's stack and every infix operator that arrives next, it
//! records whether lowering folds the first before pushing the second. Coq
//! proves its `prec` gives the same answers, so the two cannot drift.

use goat_checker::hir::{BinOp, Expr, ExprKind};
use goat_checker::lower::lower;

const TABLE_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../proofs/GoatPrecTable.v");

#[derive(Clone, Copy, PartialEq, Debug)]
enum Op {
    Or,
    And,
    Not,
    Bin(BinOp),
}

/// Every infix operator: its source spelling, and the Coq constructor.
const INFIX: [(Op, &str, &str); 14] = [
    (Op::Or, "or", "L_or"),
    (Op::And, "and", "L_and"),
    (Op::Bin(BinOp::Add), "+", "(L_bin bop_add)"),
    (Op::Bin(BinOp::Sub), "-", "(L_bin bop_sub)"),
    (Op::Bin(BinOp::Mul), "*", "(L_bin bop_mul)"),
    (Op::Bin(BinOp::Div), "/", "(L_bin bop_div)"),
    (Op::Bin(BinOp::FloorDiv), "//", "(L_bin bop_fdiv)"),
    (Op::Bin(BinOp::Mod), "%", "(L_bin bop_rem)"),
    (Op::Bin(BinOp::Lt), "<", "(L_bin bop_lt)"),
    (Op::Bin(BinOp::Lte), "<=", "(L_bin bop_lte)"),
    (Op::Bin(BinOp::Gt), ">", "(L_bin bop_gt)"),
    (Op::Bin(BinOp::Gte), ">=", "(L_bin bop_gte)"),
    (Op::Bin(BinOp::Eq), "==", "(L_bin bop_eq)"),
    (Op::Bin(BinOp::Ne), "!=", "(L_bin bop_ne)"),
];

fn lowered_root(source: &str) -> Expr {
    let lowered = lower(source).unwrap_or_else(|e| panic!("{source:?} does not parse: {e:?}"));
    assert!(
        lowered.errors.is_empty(),
        "{source:?} lowers with errors: {:?}",
        lowered.errors
    );
    lowered.root
}

fn top_operator(source: &str) -> Op {
    match &lowered_root(source).kind {
        ExprKind::Or { .. } => Op::Or,
        ExprKind::And { .. } => Op::And,
        ExprKind::Not(_) => Op::Not,
        ExprKind::Bin { op, .. } => Op::Bin(*op),
        other => panic!("{source:?} lowers to {other:?}, not an operation"),
    }
}

/// Whether `top`, already pending, is folded before `incoming` arrives.
fn folds_first(top: Op, top_text: &str, incoming: Op, incoming_text: &str) -> bool {
    if top == Op::Not {
        let source = format!("not 1 {incoming_text} 2");
        // `not 1 o 2` is `(not 1) o 2` when `not` folds first, else `not (1 o 2)`.
        return top_operator(&source) == incoming;
    }
    let source = format!("1 {top_text} 2 {incoming_text} 3");
    top_operator(&source) == incoming
}

fn precedence_table() -> String {
    let tops = std::iter::once((Op::Not, "not", "L_not")).chain(INFIX);
    let mut rows = Vec::new();
    for (top, top_text, top_coq) in tops {
        for (incoming, incoming_text, incoming_coq) in INFIX {
            let folds = folds_first(top, top_text, incoming, incoming_text);
            rows.push(format!("  ({top_coq}, {incoming_coq}, {folds})"));
        }
    }
    format!(
        "(* Generated by checker/tests/precedence.rs; do not edit. Each row is\n   \
         (top, incoming, folds): whether lowering folds the operator on top of its\n   \
         stack before it pushes the infix operator that arrives next. The Coq\n   \
         [prec] must give the same answers. *)\n\n\
         From Stdlib Require Import List PeanoNat.\n\
         Import ListNotations.\n\
         Require Import Goat.Goat_ott.\n\
         Require Import Goat.GoatPrec.\n\n\
         Definition folds_table : list (lop * lop * bool) := [\n{}\n].\n\n\
         Lemma prec_agrees :\n  \
         List.map (fun r => Nat.leb (prec (snd (fst r))) (prec (fst (fst r)))) folds_table\n  \
         = List.map snd folds_table.\n\
         Proof. reflexivity. Qed.\n",
        rows.join(";\n")
    )
}

/// `UPDATE_PRECEDENCE_TABLE=1 cargo test -p goat_checker --test precedence`
/// rewrites the table after a change to lowering's precedence.
#[test]
fn the_coq_precedence_table_matches_lowering() {
    let generated = precedence_table();
    if std::env::var_os("UPDATE_PRECEDENCE_TABLE").is_some() {
        std::fs::write(TABLE_PATH, &generated).expect("write the table");
    }
    let committed = std::fs::read_to_string(TABLE_PATH).expect("proofs/GoatPrecTable.v exists");
    assert!(
        committed == generated,
        "proofs/GoatPrecTable.v is stale; run with UPDATE_PRECEDENCE_TABLE=1 and commit"
    );
}

#[test]
fn equal_levels_fold_to_the_left_and_a_tighter_operator_on_the_right_nests() {
    assert!(folds_first(
        Op::Bin(BinOp::Sub),
        "-",
        Op::Bin(BinOp::Add),
        "+"
    ));
    assert!(!folds_first(
        Op::Bin(BinOp::Add),
        "+",
        Op::Bin(BinOp::Mul),
        "*"
    ));
    assert!(folds_first(Op::And, "and", Op::And, "and"));
}

#[test]
fn not_takes_the_operand_after_it_and_binds_looser_than_a_comparison() {
    assert!(!folds_first(Op::Not, "not", Op::Bin(BinOp::Eq), "=="));
    assert!(folds_first(Op::Not, "not", Op::And, "and"));
}

fn int(expr: &Expr) -> i64 {
    match &expr.kind {
        ExprKind::Int(n) => *n,
        _ => panic!("not an integer literal: {expr:?}"),
    }
}

/// The denotation of `-x` is `0 - x`, and of a bare `-3` the literal `-3`
/// (`proofs/GoatDen.v`, `D_neg_chain` and `D_neg_int`).
#[test]
fn a_negation_lowers_to_zero_minus_the_operand_or_a_negative_literal() {
    assert_eq!(int(&lowered_root("-3")), -3);
    let paren = lowered_root("-(3)");
    let ExprKind::Bin { op, lhs, rhs } = &paren.kind else {
        panic!("`-(3)` is not an operation");
    };
    assert_eq!((*op, int(lhs), int(rhs)), (BinOp::Sub, 0, 3));
    let twice = lowered_root("--3");
    let ExprKind::Bin { op, lhs, rhs } = &twice.kind else {
        panic!("`--3` is not an operation");
    };
    assert_eq!((*op, int(lhs), int(rhs)), (BinOp::Sub, 0, -3));
    let sum = lowered_root("-3 + 4");
    let ExprKind::Bin { op, lhs, .. } = &sum.kind else {
        panic!("`-3 + 4` is not an operation");
    };
    assert_eq!(*op, BinOp::Add);
    assert_eq!(int(lhs), -3);
}
